// Supabase one-shot setup for the Tshovani enrollment system.
// Usage: node setup-supabase.mjs <PERSONAL_ACCESS_TOKEN>
// Does: check token -> create project (if needed) -> wait ready -> run schema
//       -> verify -> fetch API keys -> write .env.local with everything Vercel needs.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const PAT = process.argv[2] || process.env.SUPABASE_PAT;
if (!PAT) {
  console.error('Usage: node setup-supabase.mjs <SUPABASE_PERSONAL_ACCESS_TOKEN>');
  process.exit(1);
}
const API = 'https://api.supabase.com/v1';
const H = {
  Authorization: `Bearer ${PAT}`,
  'Content-Type': 'application/json',
};

async function api(method, url, body) {
  const r = await fetch(API + url, {
    method,
    headers: H,
    body: body ? JSON.stringify(body) : undefined,
  });
  const text = await r.text();
  let json = null;
  try { json = text ? JSON.parse(text) : null; } catch { json = { raw: text }; }
  if (!r.ok) {
    throw new Error(`${method} ${url} -> ${r.status}: ${typeof json === 'object' ? JSON.stringify(json).slice(0, 400) : text.slice(0, 400)}`);
  }
  return json;
}

const sleep = ms => new Promise(r => setTimeout(r, ms));

async function main() {
  // 1. Who am I / can we list orgs?
  const me = await api('GET', '/user');
  console.log(`Authenticated as: ${me.email || me.username || me.id}`);
  const orgs = await api('GET', '/organizations');
  if (!orgs.length) throw new Error('No Supabase organization found on this account. Create one at supabase.com first (free).');
  const org = orgs[0];
  console.log(`Using organization: ${org.name} (${org.id})`);

  // 2. Find an existing Tshovani project or create one
  const projects = await api('GET', '/projects');
  let project = projects.find(p => p.name.toLowerCase().includes('tshovani'));
  if (project) {
    console.log(`Found existing project: ${project.name} (${project.id})`);
  } else {
    const region = 'eu-west-2'; // London — closest anycast to Zimbabwe of the free tiers
    console.log('Creating project "Tshovani-Primary"...');
    const dbPass = crypto.randomBytes(18).toString('base64url');
    project = await api('POST', '/projects', {
      org_id: org.id,
      name: 'Tshovani-Primary',
      db_pass: dbPass,
      region,
      plan: 'free',
    });
    console.log(`Project created: ${project.id}. Waiting for it to become active...`);
  }

  // 3. Wait until the project is active
  for (let i = 0; i < 60; i++) {
    const p = await api('GET', `/projects/${project.id}`);
    if (p.status === 'ACTIVE_HEALTHY') { console.log('Project is ACTIVE_HEALTHY'); break; }
    if (i === 59) throw new Error(`Project still ${p.status} after 5 minutes.`);
    await sleep(5000);
  }

  // 4. Run the schema
  const sql = fs.readFileSync(path.join(process.cwd(), 'api', 'schema.sql'), 'utf8');
  console.log('Running schema.sql ...');
  await api('POST', `/projects/${project.id}/database/query`, { query: sql });
  console.log('Schema applied.');

  // 5. Verify: table exists + insert/select a probe row
  const verify = await api('POST', `/projects/${project.id}/database/query`, {
    query: `insert into applications (ref, status, learner, guardian)
            values ('TSP-PROBE-DELETEME', 'pending',
                    '{"firstName":"Probe","lastName":"Row","dob":"2020-01-01","gender":"female","grade":"g1","notes":""}',
                    '{"name":"Probe","phone":"+263 00","email":"","relation":"parent"}')
            returning ref;`,
  });
  console.log('Insert probe OK:', JSON.stringify(verify).slice(0, 120));
  const sel = await api('POST', `/projects/${project.id}/database/query`, {
    query: `select count(*)::int as n from applications;`,
  });
  console.log('Row count now:', JSON.stringify(sel).slice(0, 120));
  await api('POST', `/projects/${project.id}/database/query`, {
    query: `delete from applications where ref = 'TSP-PROBE-DELETEME';`,
  });
  console.log('Probe cleaned up.');

  // 6. Fetch the public API keys (anon + service_role)
  const keys = await api('GET', `/projects/${project.id}/api-keys`);
  const service = keys.find(k => k.name === 'service_role' || k.type === 'service_role');
  const anon = keys.find(k => k.name === 'anon' || k.type === 'anon');
  const env = [
    `# Generated by setup-supabase.mjs on ${new Date().toISOString()}`,
    `# NEVER commit this file or share the service key.`,
    `SUPABASE_URL=https://${project.id}.supabase.co`,
    service ? `SUPABASE_SERVICE_KEY=${service.api_key ?? service.key}` : '# service key not found - copy from dashboard',
    anon ? `SUPABASE_ANON_KEY=${anon.api_key ?? anon.key}` : '# anon key not found - copy from dashboard',
  ].join('\n');
  fs.writeFileSync('.env.local', env + '\n');
  console.log('\nWrote .env.local with SUPABASE_URL and keys.');
  console.log(`Dashboard: https://supabase.com/dashboard/project/${project.id}`);
  console.log('\nNext: I will push these to Vercel as env vars once you approve the Vercel login.');
}

main().catch(err => {
  console.error('FAILED:', err.message);
  process.exit(1);
});
